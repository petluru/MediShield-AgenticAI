"""Formats eval results into EVAL_REPORT.md — the assignment's own
requirement to "report against [the 70%/60% bar] explicitly so it's obvious
whether the system clears it" (assignment_02_multimodal_ai.md SS"Evaluation
Criteria", PROJECT_PLAN.md SS9)."""

from collections import Counter

from backend.evals.scoring import CaseResult, WeightedScore


def _mismatches(results: list[CaseResult]) -> list[CaseResult]:
    return [r for r in results if r.error or r.actual_decision != r.expected_decision]


def format_report(results: list[CaseResult], score: WeightedScore) -> str:
    lines = [
        "# Eval Report",
        "",
        "Auto-generated by `backend/scripts/run_evals.py` from "
        "`backend/evals/harness.py` results, scored per "
        "`assignment_02_multimodal_ai.md`'s Evaluation Criteria table — do "
        "not hand-edit this file.",
        "",
        f"**{len(results)} cases evaluated** ({sum(1 for r in results if r.error)} errored).",
        "",
        "## Auto-Scored Criteria",
        "",
        "| Criterion | Weight | Score |",
        "|---|---|---|",
        f"| Classification Accuracy | 20% | {score.classification_accuracy:.1%} |",
        f"| Extraction Completeness | 20% | {score.extraction_completeness:.1%} |",
        f"| Decision Correctness | 25% | {score.decision_correctness:.1%} |",
        f"| **Auto-scored subtotal** | **{score.auto_scored_weight:.0%}** | "
        f"**{score.auto_scored_subtotal:.1%} (of the {score.auto_scored_weight:.0%} weight)** |",
        "",
        "## Not Auto-Scored (need manual review or unbuilt components)",
        "",
        "| Criterion | Weight | Why not scored here |",
        "|---|---|---|",
        f"| Policy Retrieval Quality | {score.not_auto_scored['policy_retrieval_quality']:.0%} | "
        "Assignment's own spec calls for a manual spot-check, not an automated metric |",
        f"| UI Functionality | {score.not_auto_scored['ui_functionality']:.0%} | No UI built yet (task #15) |",
        f"| Code Quality & Structure | {score.not_auto_scored['code_quality_and_structure']:.0%} | "
        "Structural/manual review criterion, not a per-case dataset metric |",
        "",
        "## Passing Bar (assignment_02_multimodal_ai.md)",
        "",
        f"- Decision Correctness >= 60%: **{'PASS' if score.passes_decision_correctness_bar else 'FAIL'}** "
        f"({score.decision_correctness:.1%})",
        "- Overall >= 70%: **cannot be fully determined by this harness alone** — "
        "35% of the weighted score (Policy Retrieval Quality, UI Functionality, "
        "Code Quality) needs manual review or components not yet built. "
        f"Auto-scored subtotal alone: {score.auto_scored_subtotal:.1%} of a possible "
        f"{score.auto_scored_weight:.0%}.",
        "",
    ]

    mismatches = _mismatches(results)
    if mismatches:
        lines += [
            f"## Mismatches ({len(mismatches)})",
            "",
            "| Doc ID | Category | Expected | Actual | Error |",
            "|---|---|---|---|---|",
        ]
        for r in mismatches:
            expected = r.expected_decision.value
            actual = r.actual_decision.value if r.actual_decision else "—"
            lines.append(f"| {r.doc_id} | {r.category} | {expected} | {actual} | {r.error or ''} |")
        lines.append("")

    lines += [
        "## Category Breakdown",
        "",
        "| Category | Cases | Decision matches |",
        "|---|---|---|",
    ]
    by_category = Counter(r.category for r in results)
    for category in sorted(by_category):
        cat_results = [r for r in results if r.category == category]
        matches = sum(1 for r in cat_results if r.actual_decision == r.expected_decision)
        lines.append(f"| {category} | {len(cat_results)} | {matches}/{len(cat_results)} |")

    return "\n".join(lines) + "\n"
